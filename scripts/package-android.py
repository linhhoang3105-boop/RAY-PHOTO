"""Export the Android source project, without dependencies, private keys or build output."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from hashlib import sha256
import json
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
PREFIX = 'RAY_PHOTO_Android_v42'
APP_ID = 'com.linhlinh.rayphoto'
VERSION = 42

def selected():
    roots = ['dist', 'android', 'native', 'source/editor']
    for folder in roots:
        for p in sorted((ROOT / folder).rglob('*')):
            if not p.is_file() or p.is_symlink():
                continue
            r = p.relative_to(ROOT)
            if any(x in r.parts for x in ['node_modules', '.gradle', '.idea', 'build', '.git']):
                continue
            if p.name.startswith('__qa') or p.name in ['local.properties', '.DS_Store'] or p.suffix.lower() in ['.jks', '.keystore']:
                continue
            if r.as_posix().startswith(('dist/client/', 'dist/server/', 'dist/.openai/')):
                continue
            if r.as_posix().startswith('android/app/src/main/assets/'):
                continue  # Generated by cap sync from dist; keep one copy of the web assets.
            yield r, p.read_bytes()
    for name in ['package.json', 'package-lock.json', 'capacitor.config.json', 'scripts/build-native-bridge.mjs', 'scripts/assemble-source.mjs', 'scripts/build-preset-bases.mjs', 'scripts/build-layer-inspector.mjs', 'ANDROID-QUICKSTART.md', 'STORE-RELEASE.md']:
        yield Path(name), (ROOT / name).read_bytes()

def main(output):
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    hashes = {}
    with ZipFile(output, 'w', ZIP_DEFLATED, compresslevel=9) as z:
        def add(name, data):
            if isinstance(data, str):
                data = data.encode('utf-8')
            z.writestr(PREFIX + '/' + name, data)
            hashes[name] = sha256(data).hexdigest()
        for r, data in selected():
            name = r.as_posix()
            if name == 'capacitor.config.json':
                config = json.loads(data)
                config['appId'] = APP_ID
                data = (json.dumps(config, ensure_ascii=False, indent=2) + '\n').encode()
            if name.startswith('android/') and r.suffix in ['.java', '.gradle', '.xml']:
                text = data.decode('utf-8').replace('vn.buongtoi.studio', APP_ID)
                if name == 'android/app/build.gradle':
                    text = re.sub(r'versionCode\s+\d+', 'versionCode ' + str(VERSION), text)
                    text = re.sub(r'versionName\s+"[^"]+"', 'versionName "1.0.0"', text)
                data = text.encode()
                name = name.replace('java/vn/buongtoi/studio/', 'java/com/linhlinh/rayphoto/')
            add(name, data)
        scripts = {
            '01_CHUAN_BI_ANDROID.bat': '@echo off\nchcp 65001 >nul\ncd /d "%~dp0"\nwhere node >nul 2>&1\nif errorlevel 1 (\n echo Cai Node.js 22.21.1 tro len truoc.\n pause\n exit /b 1\n)\ncall npm ci\nif errorlevel 1 goto fail\ncall npm run native:sync\nif errorlevel 1 goto fail\necho Da dong bo. Chay 02_MO_ANDROID_STUDIO.bat.\npause\nexit /b 0\n:fail\necho Chua chuan bi xong. Xem thong bao loi ben tren.\npause\nexit /b 1\n',
            '02_MO_ANDROID_STUDIO.bat': '@echo off\nchcp 65001 >nul\ncd /d "%~dp0"\ncall npx cap open android\nif errorlevel 1 echo Mo Android Studio va chon thu muc android.\npause\n',
            '03_DONG_BO_WEB.bat': '@echo off\nchcp 65001 >nul\ncd /d "%~dp0"\ncall npm run native:sync\nif errorlevel 1 (\n echo Chua dong bo duoc. Xem loi ben tren.\n) else (\n echo Da dong bo dist sang Android. Build lai trong Android Studio.\n)\npause\n'
        }
        for name, body in scripts.items():
            add(name, body.replace('\n', '\r\n'))
        add('DOC_TRUOC.md', (ROOT / 'ANDROID-QUICKSTART.md').read_bytes())
        add('CH_PLAY/icon-512.png', (ROOT / 'dist/icons/icon-512.png').read_bytes())
        add('.gitignore', 'node_modules/\nandroid/.gradle/\nandroid/app/build/\nandroid/build/\nandroid/local.properties\n*.jks\n*.keystore\n')
        manifest = {'version': VERSION, 'app_id': APP_ID, 'source_commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(), 'android_binary_compiled': False, 'signed': False, 'files': hashes}
        add('KIEM_TRA_NGUON.json', json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    with ZipFile(output) as z:
        assert z.testzip() is None
        assert any(n.endswith('/BuongToiMediaPlugin.java') for n in z.namelist())
        assert any(n.endswith('/dist/photobooth/index.html') for n in z.namelist())
        assert not any('/__qa' in n or '/node_modules/' in n or '/.git/' in n for n in z.namelist())
    print(json.dumps({'path': str(output), 'bytes': output.stat().st_size, 'files': len(hashes) + 1, 'app_id': APP_ID, 'version_code': VERSION, 'compiled': False}))

if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('Pass an absolute output .zip path.')
    main(sys.argv[1])
